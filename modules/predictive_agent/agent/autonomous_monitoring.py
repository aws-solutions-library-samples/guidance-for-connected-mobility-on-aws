    async def _create_monitoring_profile(self, vehicle_id: str) -> VehicleMonitoringProfile:
        """Create monitoring profile for a vehicle"""
        
        # Get vehicle risk assessment
        risk_level = await self._assess_vehicle_risk(vehicle_id)
        
        # Determine monitoring strategy
        if risk_level == 'critical':
            strategy = MonitoringStrategy.CONTINUOUS
            frequency = self.high_risk_interval
        elif risk_level == 'high':
            strategy = MonitoringStrategy.ADAPTIVE_POLLING
            frequency = timedelta(seconds=60)
        else:
            strategy = MonitoringStrategy.PATTERN_BASED
            frequency = self.base_monitoring_interval
        
        return VehicleMonitoringProfile(
            vehicle_id=vehicle_id,
            risk_level=risk_level,
            monitoring_frequency=frequency,
            critical_thresholds={},
            learned_patterns=[],
            prediction_horizon=timedelta(hours=24),
            last_analysis=datetime.utcnow(),
            monitoring_strategy=strategy
        )
    
    async def _assess_vehicle_risk(self, vehicle_id: str) -> str:
        """Assess vehicle risk level"""
        # In production, use ML model or rule-based assessment
        return 'medium'
    
    def _calculate_monitoring_interval(self, profile: VehicleMonitoringProfile) -> timedelta:
        """Calculate dynamic monitoring interval based on risk"""
        
        base_interval = profile.monitoring_frequency
        
        # Adjust based on risk level
        if profile.risk_level == 'critical':
            return base_interval
        elif profile.risk_level == 'high':
            return base_interval * 2
        else:
            return base_interval * 4